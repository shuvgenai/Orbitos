-- FD-38 stage S3: set_access(), the only sanctioned way a person's access can change.
--
-- After S2b nobody can write `profiles.access` at all -- the access-immutability trigger
-- refuses every direct UPDATE unless the effective user is the schema owner, which no client
-- ever is. This adds the governed path, and it is what makes the org-admin model usable:
-- "the org admin builds out the org structure" rests on this function.
--
-- FIVE GUARDS, IN THE ORDER 1, 3, 4, 2, 5 -- NOT 1 TO 5. FD-14 settles the order and it is
-- load-bearing twice over:
--
--   * GUARD 4 MUST PRECEDE GUARD 2. A super admin carries no org_id (`super_has_no_org`), so
--     the office check would refuse them first and guard 4 would never run.
--   * GUARD 1 MUST BE FIRST. 0009 moved it there to close a ROLE ORACLE that 0008 opened:
--     the refusals differ, so the order in which you are refused leaks whether a target
--     exists and which office they are in. Guards 1 and 2 deliberately share one sentence --
--     "that change is not available to you" -- for the same reason. A function that answered
--     differently would be a directory lookup.
--
-- Read 0009's header in orbitos-infra before reordering anything here.
--
-- GUARD 5 IS UNREACHABLE WHILE THIS ORDER STANDS, AND THAT IS NOT A DEFECT. Guard 1 requires
-- the caller to be an admin, and guard 3 refuses the caller changing themselves -- so either
-- the target is the caller (already refused) or a second admin exists and the count is at
-- least 1. Guard 5 is the second lock behind guard 3. Do not "fix" it by reordering.
--
-- GUARD 6 IS WHY THIS MIGRATION ALSO CREATES audit_log. The function's last act is an audit
-- row, and that table was not in S2b's scope -- S2b ported the four org tables only. The
-- function cannot be ported without it, which is the sort of thing that is cheaper to
-- discover by reading the body than by watching a migration fail. Column names are 0001's
-- applied ones, not D5's reference, which was written against a differently shaped table:
-- FD-13.
--
-- NO FORCE ROW LEVEL SECURITY, deliberately, for the reason migration 20261117000200
-- records: every policy calls current_org(), a SECURITY DEFINER helper that reads a guarded
-- table, and FORCE makes that recurse until Postgres gives up. The owner split is what
-- constrains the runtime instead.

-- ---------------------------------------------------------------- audit_log
-- org_id is NULLABLE on purpose: an action taken before the office row exists, or by the
-- instance itself, has no office. A sentinel org row inside RLS keyed on org_id is worse
-- than the NULL it removes. FD-15.
CREATE TABLE IF NOT EXISTS orbitcrew.audit_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    occurred_at timestamp with time zone DEFAULT now() NOT NULL,
    actor text NOT NULL,
    action text NOT NULL,
    entity_type text NOT NULL,
    entity_id text,
    fields text[] DEFAULT '{}'::text[] NOT NULL,
    detail jsonb DEFAULT '{}'::jsonb NOT NULL,
    org_id uuid,
    CONSTRAINT audit_log_pkey PRIMARY KEY (id),
    CONSTRAINT audit_log_org_id_fkey FOREIGN KEY (org_id) REFERENCES orbitcrew.orgs(id)
);

CREATE INDEX IF NOT EXISTS audit_log_org_id_idx   ON orbitcrew.audit_log (org_id);
CREATE INDEX IF NOT EXISTS audit_log_entity_idx   ON orbitcrew.audit_log (entity_type, entity_id);
CREATE INDEX IF NOT EXISTS audit_log_occurred_idx ON orbitcrew.audit_log (occurred_at DESC);

ALTER TABLE orbitcrew.audit_log ENABLE ROW LEVEL SECURITY;

-- SELECT only, and admins only. There is no INSERT policy on purpose: rows arrive through
-- SECURITY DEFINER functions, never from a client, so a client that could write here could
-- forge the record of its own actions.
DO $p$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies
                    WHERE schemaname = 'orbitcrew' AND tablename = 'audit_log'
                      AND policyname = 'audit_log_admin_select') THEN
        CREATE POLICY audit_log_admin_select ON orbitcrew.audit_log FOR SELECT
            USING (((org_id = orbitcrew.current_org())
                AND (orbitcrew.current_access() = 'admin'::orbitcrew.access_role)));
    END IF;
END
$p$;

-- ---------------------------------------------------------------- set_access
-- Verbatim from the running infra database via pg_get_functiondef.

CREATE OR REPLACE FUNCTION orbitcrew.set_access(target uuid, new_access orbitcrew.access_role)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'orbitcrew', 'pg_temp'
AS $function$
DECLARE
    caller        uuid := orbitcrew.current_user_id();
    caller_org    uuid := orbitcrew.current_org();
    target_access orbitcrew.access_role;
    target_org    uuid;
    admins        integer;
BEGIN
    -- GUARD 1 — the caller is an Org Admin.
    -- First, so that every refusal below is reachable only by someone already inside
    -- the office. Everything a non-admin caller can learn from this function is the one
    -- generic sentence.
    IF orbitcrew.current_access() IS DISTINCT FROM 'admin' THEN
        RAISE EXCEPTION 'that change is not available to you'
            USING ERRCODE = 'insufficient_privilege';
    END IF;

    -- Read the target WITHOUT an office filter. Guard 4 has to be able to see a target
    -- the caller could never reach, or it cannot judge one.
    SELECT p.access, p.org_id INTO target_access, target_org
      FROM orbitcrew.profiles p
     WHERE p.id = target;

    -- GUARD 3 — nobody changes their own access. (0007)
    IF target = caller THEN
        RAISE EXCEPTION 'you cannot change your own access'
            USING ERRCODE = 'insufficient_privilege';
    END IF;

    -- GUARD 4 — `super` is neither granted nor touched from inside an office. (0008)
    IF new_access = 'super' OR target_access = 'super' THEN
        RAISE EXCEPTION 'operator access is not granted from an office'
            USING ERRCODE = 'insufficient_privilege';
    END IF;

    -- GUARD 2 — the target is in the caller's own office.
    -- One refusal for every reason: no such person, another office, not your place to
    -- ask. A function that answered differently would be a directory lookup.
    IF target_access IS NULL OR target_org IS DISTINCT FROM caller_org THEN
        RAISE EXCEPTION 'that change is not available to you'
            USING ERRCODE = 'insufficient_privilege';
    END IF;

    IF target_access = new_access THEN
        RETURN;
    END IF;

    -- GUARD 5 — the office keeps at least one Org Admin.
    IF target_access = 'admin' THEN
        SELECT count(*) INTO admins
          FROM orbitcrew.profiles p
         WHERE p.org_id = caller_org AND p.access = 'admin' AND p.id <> target;

        IF admins < 1 THEN
            RAISE EXCEPTION 'an office must keep at least one Org Admin'
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
    END IF;

    UPDATE orbitcrew.profiles SET access = new_access WHERE id = target;

    -- GUARD 6 — every change through this function writes an audit row.
    -- Applied column names from `0001`, not D5's reference, which was written against a
    -- differently shaped table. Recorded as FD-13.
    INSERT INTO orbitcrew.audit_log (org_id, actor, action, entity_type, entity_id, fields, detail)
    VALUES (caller_org,
            COALESCE(caller::text, 'unknown'),
            'access.changed',
            'profile',
            target::text,
            ARRAY['access'],
            jsonb_build_object('from', target_access::text, 'to', new_access::text));
END
$function$;

-- ---------------------------------------------------------------- grants
DO $grant$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'orbit_app') THEN
        -- SELECT only on audit_log: the runtime reads its own office's history and writes
        -- nothing. The INSERT happens inside set_access(), which runs as the owner.
        EXECUTE 'GRANT SELECT ON orbitcrew.audit_log TO orbit_app';
        EXECUTE 'GRANT EXECUTE ON FUNCTION orbitcrew.set_access(uuid, orbitcrew.access_role) TO orbit_app';
    END IF;
END
$grant$;
